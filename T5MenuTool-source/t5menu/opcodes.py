OPERATOR_BY_TOKEN = {v: k for k, v in OPERATORS.items()}
FUNCTION_BY_NAME = {n.lower(): i + FUNCTION_BASE for i, n in enumerate(FUNCTIONS) if i}


def command_name(index: int) -> str:
    if index in OPERATORS:
        return OPERATORS[index]
    f = index - FUNCTION_BASE
    if 0 < f < len(FUNCTIONS):
        return FUNCTIONS[f] + "()"
    return f"cmd#{index}"


def command_index(token: str) -> int:
    if token in OPERATOR_BY_TOKEN:
        return OPERATOR_BY_TOKEN[token]
    if token.startswith("cmd#"):
        return int(token[4:])
    if token.endswith("()") and token[:-2].lower() in FUNCTION_BY_NAME:
        return FUNCTION_BY_NAME[token[:-2].lower()]
    raise ValueError(f"unknown expression command {token!r}")
